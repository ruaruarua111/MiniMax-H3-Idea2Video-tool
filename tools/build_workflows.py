def _node(nodes: list[dict[str, Any]], node_id: int) -> dict[str, Any]:
    for item in nodes:
        if item.get("id") == node_id:
            return item
    raise ValueError(f"Missing node {node_id}")


def _input_slot(node: dict[str, Any], name: str) -> int:
    for index, item in enumerate(node.get("inputs", [])):
        if item.get("name") == name:
            return index
    raise ValueError(f"Node {node.get('id')} has no input named {name!r}")


def _output_slot(node: dict[str, Any], name: str) -> int:
    for index, item in enumerate(node.get("outputs", [])):
        if item.get("name") == name:
            return index
    raise ValueError(f"Node {node.get('id')} has no output named {name!r}")


def _new_node(
    template: dict[str, Any],
    node_id: int,
    title: str,
    position: tuple[float, float],
    widgets: list[Any] | None = None,
) -> dict[str, Any]:
    result = copy.deepcopy(template)
    result["id"] = node_id
    result["title"] = title
    result["pos"] = list(position)
    result["order"] = node_id
    if widgets is not None:
        result["widgets_values"] = widgets
    for item in result.get("inputs", []):
        item["link"] = None
    for item in result.get("outputs", []):
        item["links"] = []
    return result


def _runs(indices: Iterable[int]) -> list[tuple[int, int]]:
    values = list(indices)
    if not values:
        return []
    result: list[tuple[int, int]] = []
    start = previous = values[0]
    for value in values[1:]:
        if value != previous + 1:
            result.append((start, previous - start + 1))
            start = value
        previous = value
    result.append((start, previous - start + 1))
    return result


class SubgraphEditor:
    def __init__(self, subgraph: dict[str, Any]) -> None:
        self.subgraph = subgraph
        self.nodes: list[dict[str, Any]] = subgraph["nodes"]
        self.links: list[dict[str, Any]] = subgraph["links"]
        self.next_node_id = max(int(node["id"]) for node in self.nodes) + 1
        self.next_link_id = max(int(link["id"]) for link in self.links) + 1

    def add_node(self, node: dict[str, Any]) -> int:
        self.nodes.append(node)
        self.next_node_id = max(self.next_node_id, int(node["id"]) + 1)
        return int(node["id"])

    def allocate_node_id(self) -> int:
        result = self.next_node_id
        self.next_node_id += 1
        return result

    def add_link(
        self,
        origin_id: int,
        origin_slot: int,
        target_id: int,
        target_slot: int,
        value_type: str,
    ) -> int:
        link_id = self.next_link_id
        self.next_link_id += 1
        self.links.append(
            {
                "id": link_id,
                "origin_id": origin_id,
                "origin_slot": origin_slot,
                "target_id": target_id,
                "target_slot": target_slot,
                "type": value_type,
            }
        )
        return link_id

    def rebuild_references(self) -> None:
        node_map = {int(node["id"]): node for node in self.nodes}
        for node in self.nodes:
            for item in node.get("inputs", []):
                item["link"] = None
            for item in node.get("outputs", []):
                item["links"] = []
        for item in self.subgraph.get("inputs", []):
            item["linkIds"] = []
        for item in self.subgraph.get("outputs", []):
            item["linkIds"] = []

        for link in self.links:
            link_id = int(link["id"])
            origin_id = int(link["origin_id"])
            target_id = int(link["target_id"])
            if origin_id == -10:
                self.subgraph["inputs"][int(link["origin_slot"])]["linkIds"].append(link_id)
            else:
                origin = node_map[origin_id]
                origin["outputs"][int(link["origin_slot"])]["links"].append(link_id)
            if target_id == -20:
                outputs = self.subgraph.get("outputs", [])
                if isinstance(outputs, dict):
                    outputs = [outputs]
                    self.subgraph["outputs"] = outputs
                outputs[int(link["target_slot"])]["linkIds"].append(link_id)
            else:
                target = node_map[target_id]
                slot = int(link["target_slot"])
                if target["inputs"][slot].get("link") is not None:
                    raise ValueError(f"Input already linked: node={target_id}, slot={slot}")
                target["inputs"][slot]["link"] = link_id

        self.subgraph["state"]["lastNodeId"] = max(node_map)
        self.subgraph["state"]["lastLinkId"] = max(int(link["id"]) for link in self.links)


def _rebuild_top_level_references(workflow: dict[str, Any]) -> None:
    nodes = workflow["nodes"]
    node_map = {int(node["id"]): node for node in nodes}
    for node in nodes:
        for item in node.get("inputs", []):
            item["link"] = None
        for item in node.get("outputs", []):
            item["links"] = []
    for link in workflow["links"]:
        link_id, origin_id, origin_slot, target_id, target_slot, _type = link
        node_map[int(origin_id)]["outputs"][int(origin_slot)]["links"].append(int(link_id))
        target = node_map[int(target_id)]
        if target["inputs"][int(target_slot)].get("link") is not None:
            raise ValueError(f"Top-level input already linked: node={target_id}, slot={target_slot}")
        target["inputs"][int(target_slot)]["link"] = int(link_id)
    workflow["last_node_id"] = max(node_map)
    workflow["last_link_id"] = max(int(link[0]) for link in workflow["links"])


