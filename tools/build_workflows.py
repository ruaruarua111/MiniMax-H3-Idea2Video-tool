def _configure_subgraph(workflow: dict[str, Any], mode: str) -> None:
    subgraph = workflow["definitions"]["subgraphs"][0]
    subgraph["name"] = f"MiniMax H3 {mode} INT8 Turbo v4 8-step HQ 9x16 7s 1080p"
    nodes = subgraph["nodes"]
    selector_template = copy.deepcopy(
        next(node for node in nodes if node.get("type") == "ImageFromBatch")
    )
    batch_template = copy.deepcopy(
        next(node for node in nodes if node.get("type") == "ImageBatch")
    )
    condition_scale_template = copy.deepcopy(
        next(
            node
            for node in nodes
            if node.get("type") == "ImageScale"
            and "conditioning canvas" in str(node.get("title") or "").lower()
        )
    )
    exact_scale_template = copy.deepcopy(
        next(
            node
            for node in nodes
            if node.get("type") == "ImageScale"
            and "exact output frame 0" in str(node.get("title") or "").lower()
        )
    )
    h3_source = next(node for node in nodes if node.get("type") == "MiniMaxH3ImageToVideo")
    video_decode_source = next(node for node in nodes if node.get("type") == "VAEDecode")
    audio_decode_source = next(node for node in nodes if node.get("type") == "VAEDecodeAudio")
    upscale_loader_source = next(node for node in nodes if node.get("type") == "UpscaleModelLoader")
    upscale_source = next(node for node in nodes if node.get("type") == "ImageUpscaleWithModel")
    final_scale_source = next(
        node
        for node in nodes
        if node.get("type") == "ImageScale"
        and int(node["id"]) not in {int(condition_scale_template["id"]), int(exact_scale_template["id"])}
    )
    trim_audio_source = next(node for node in nodes if node.get("type") == "TrimAudioDuration")
    final_output_link = next(
        link
        for link in subgraph["links"]
        if int(link["target_id"]) == -20 and int(link["target_slot"]) == 0
    )
    final_video_source = _node(nodes, int(final_output_link["origin_id"]))
    if final_video_source.get("type") != "CreateVideo":
        raise ValueError("Subgraph output 0 is not produced by CreateVideo")

    retained_post_ids = {
        int(upscale_loader_source["id"]),
        int(upscale_source["id"]),
        int(final_scale_source["id"]),
        int(trim_audio_source["id"]),
        int(final_video_source["id"]),
    }
    removable_ids = {
        int(node["id"])
        for node in nodes
        if node.get("type") in {"ImageFromBatch", "ImageBatch"}
        or (
            node.get("type") == "ImageScale"
            and int(node["id"]) != int(final_scale_source["id"])
        )
        or (
            node.get("type") == "CreateVideo"
            and int(node["id"]) != int(final_video_source["id"])
        )
    }
    subgraph["nodes"] = [node for node in nodes if int(node["id"]) not in removable_ids]
    subgraph["links"] = [
        link
        for link in subgraph["links"]
        if int(link["origin_id"]) not in retained_post_ids | removable_ids
        and int(link["target_id"]) not in retained_post_ids | removable_ids
        and not (int(link["origin_id"]) == -10 and int(link["origin_slot"]) in (0, 1))
        and not (
            int(link["target_id"]) == int(h3_source["id"])
            and int(link["target_slot"])
            in (
                _input_slot(h3_source, "first_frame"),
                _input_slot(h3_source, "last_frame"),
            )
        )
    ]
    outputs = subgraph.get("outputs", [])
    if isinstance(outputs, list):
        subgraph["outputs"] = outputs[:1]

    editor = SubgraphEditor(subgraph)
    nodes = editor.nodes
    h3_node = _node(nodes, int(h3_source["id"]))
    h3_node["widgets_values"][0] = GENERIC_PROMPTS[mode]
    h3_node["widgets_values"][1:4] = [768, 1344, MODEL_FRAMES]

    # Keep stable IDs for the proven output nodes, but clear their old connections.
    upscale_loader = _node(nodes, int(upscale_loader_source["id"]))
    upscale = _node(nodes, int(upscale_source["id"]))
    final_scale = _node(nodes, int(final_scale_source["id"]))
    trim_audio = _node(nodes, int(trim_audio_source["id"]))
    create_video = _node(nodes, int(final_video_source["id"]))
    trim_audio["widgets_values"] = [0, DURATION_SECONDS]
    trim_audio["title"] = "Trim native audio to exactly 7 seconds"
    create_video["widgets_values"] = [FPS, 10]

    # The same nearest-position mapping is used for every mode. Exact reference
    # pictures replace the selected endpoints only after generation.
    if mode == "T2VA":
        generated_indices = SELECTED_INDICES
    elif mode == "I2VA":
        generated_indices = SELECTED_INDICES[1:]
    else:
        generated_indices = SELECTED_INDICES[1:-1]

    selector_ids: list[int] = []
    for run_index, (start, length) in enumerate(_runs(generated_indices)):
        node_id = editor.allocate_node_id()
        end = start + length - 1
        selector = _new_node(
            selector_template,
            node_id,
            f"Keep generated frames {start}-{end}",
            (-360, 5250 + run_index * 135),
            [start, length],
        )
        editor.add_node(selector)
        editor.add_link(
            int(video_decode_source["id"]),
            0,
            node_id,
            _input_slot(selector, "image"),
            "IMAGE",
        )
        selector_ids.append(node_id)

    current_source = selector_ids[0]
    current_slot = 0
    for batch_index, selector_id in enumerate(selector_ids[1:], start=1):
        node_id = editor.allocate_node_id()
        batch = _new_node(
            batch_template,
            node_id,
            f"Join remapped segment {batch_index + 1}",
            (20 + batch_index * 305, 5350 + batch_index * 85),
            [],
        )
        editor.add_node(batch)
        editor.add_link(current_source, current_slot, node_id, 0, "IMAGE")
        editor.add_link(selector_id, 0, node_id, 1, "IMAGE")
        current_source = node_id
        current_slot = 0

    editor.add_link(
        int(upscale_loader["id"]),
        _output_slot(upscale_loader, "UPSCALE_MODEL"),
        int(upscale["id"]),
        _input_slot(upscale, "upscale_model"),
        "UPSCALE_MODEL",
    )
    editor.add_link(
        current_source,
        current_slot,
        int(upscale["id"]),
        _input_slot(upscale, "image"),
        "IMAGE",
    )
    editor.add_link(
        int(upscale["id"]),
        _output_slot(upscale, "IMAGE"),
        int(final_scale["id"]),
        _input_slot(final_scale, "image"),
        "IMAGE",
    )
    final_scale["title"] = "Resize remapped generated frames to 1080x1920"

    exact_sources: dict[str, int] = {}
    if mode in ("I2VA", "FL2VA"):
        condition1_id = editor.allocate_node_id()
        condition1 = _new_node(
            condition_scale_template,
            condition1_id,
            "Picture 1 conditioning canvas 768x1344",
            (-1330, 5260),
            ["lanczos", 768, 1344, "center"],
        )
        editor.add_node(condition1)
        editor.add_link(-10, 0, condition1_id, 0, "IMAGE")
        editor.add_link(
            condition1_id,
            0,
            int(h3_node["id"]),
            _input_slot(h3_node, "first_frame"),
            "IMAGE",
        )

        exact1_id = editor.allocate_node_id()
        exact1 = _new_node(
            exact_scale_template,
            exact1_id,
            "Exact output frame 0 from Picture 1",
            (610, 6640),
            ["lanczos", 1080, 1920, "center"],
        )
        editor.add_node(exact1)
        editor.add_link(-10, 0, exact1_id, 0, "IMAGE")
        exact_sources["first"] = exact1_id

    if mode == "FL2VA":
        condition2_id = editor.allocate_node_id()
        condition2 = _new_node(
            condition_scale_template,
            condition2_id,
            "Picture 2 conditioning canvas 768x1344",
            (-980, 5260),
            ["lanczos", 768, 1344, "center"],
        )
        editor.add_node(condition2)
        editor.add_link(-10, 1, condition2_id, 0, "IMAGE")
        editor.add_link(
            condition2_id,
            0,
            int(h3_node["id"]),
            _input_slot(h3_node, "last_frame"),
            "IMAGE",
        )

        exact2_id = editor.allocate_node_id()
        exact2 = _new_node(
            exact_scale_template,
            exact2_id,
            "Exact output frame 167 from Picture 2",
            (950, 6640),
            ["lanczos", 1080, 1920, "center"],
        )
        editor.add_node(exact2)
        editor.add_link(-10, 1, exact2_id, 0, "IMAGE")
        exact_sources["last"] = exact2_id

    image_source = int(final_scale["id"])
    image_slot = _output_slot(final_scale, "IMAGE")
    if mode in ("I2VA", "FL2VA"):
        first_batch_id = editor.allocate_node_id()
        first_batch = _new_node(
            batch_template,
            first_batch_id,
            "Exact Picture 1 + uniformly remapped generated frames",
            (1280, 5500),
            [],
        )
        editor.add_node(first_batch)
        editor.add_link(exact_sources["first"], 0, first_batch_id, 0, "IMAGE")
        editor.add_link(image_source, image_slot, first_batch_id, 1, "IMAGE")
        image_source = first_batch_id
        image_slot = 0

    if mode == "FL2VA":
        final_batch_id = editor.allocate_node_id()
        final_batch = _new_node(
            batch_template,
            final_batch_id,
            "Append exact Picture 2 as output frame 167",
            (1590, 5500),
            [],
        )
        editor.add_node(final_batch)
        editor.add_link(image_source, image_slot, final_batch_id, 0, "IMAGE")
        editor.add_link(exact_sources["last"], 0, final_batch_id, 1, "IMAGE")
        image_source = final_batch_id
        image_slot = 0

    editor.add_link(
        image_source,
        image_slot,
        int(create_video["id"]),
        _input_slot(create_video, "images"),
        "IMAGE",
    )
    editor.add_link(
        int(audio_decode_source["id"]),
        0,
        int(trim_audio["id"]),
        _input_slot(trim_audio, "audio"),
        "AUDIO",
    )
    editor.add_link(
        int(trim_audio["id"]),
        0,
        int(create_video["id"]),
        _input_slot(create_video, "audio"),
        "AUDIO",
    )
    editor.add_link(int(create_video["id"]), 0, -20, 0, "VIDEO")
    editor.rebuild_references()


def validate_workflow(workflow: dict[str, Any], mode: str) -> list[str]:
    errors: list[str] = []
    top_nodes = {int(node["id"]): node for node in workflow.get("nodes", [])}
    top_link_ids = {int(link[0]) for link in workflow.get("links", [])}
    if len(top_link_ids) != len(workflow.get("links", [])):
        errors.append("duplicate top-level link ID")
    for link in workflow.get("links", []):
        link_id, origin_id, origin_slot, target_id, target_slot, _type = link
        if int(origin_id) not in top_nodes or int(target_id) not in top_nodes:
            errors.append(f"top-level dangling node in link {link_id}")
            continue
        if int(origin_slot) >= len(top_nodes[int(origin_id)].get("outputs", [])):
            errors.append(f"top-level invalid origin slot in link {link_id}")
        if int(target_slot) >= len(top_nodes[int(target_id)].get("inputs", [])):
            errors.append(f"top-level invalid target slot in link {link_id}")

    subgraph = workflow["definitions"]["subgraphs"][0]
    nodes = {int(node["id"]): node for node in subgraph["nodes"]}
    link_ids = {int(link["id"]) for link in subgraph["links"]}
    if len(link_ids) != len(subgraph["links"]):
        errors.append("duplicate subgraph link ID")
    for link in subgraph["links"]:
        link_id = int(link["id"])
        origin_id = int(link["origin_id"])
        target_id = int(link["target_id"])
        if origin_id != -10 and origin_id not in nodes:
            errors.append(f"subgraph dangling origin in link {link_id}")
        if target_id != -20 and target_id not in nodes:
            errors.append(f"subgraph dangling target in link {link_id}")

    h3 = next(node for node in nodes.values() if node.get("type") == "MiniMaxH3ImageToVideo")
    first_link = h3["inputs"][_input_slot(h3, "first_frame")].get("link")
    last_link = h3["inputs"][_input_slot(h3, "last_frame")].get("link")
    expected = {
        "T2VA": (False, False, 0),
        "I2VA": (True, False, 1),
        "FL2VA": (True, True, 2),
    }[mode]
    if bool(first_link) != expected[0] or bool(last_link) != expected[1]:
        errors.append(f"{mode} first/last frame connection mismatch")
    load_images = [node for node in top_nodes.values() if node.get("type") == "LoadImage"]
    if len(load_images) != expected[2]:
        errors.append(f"{mode} expected {expected[2]} LoadImage nodes")

    if h3["widgets_values"][1:4] != [768, 1344, MODEL_FRAMES]:
        errors.append("native resolution or frame count mismatch")
    lora = next(node for node in nodes.values() if node.get("type") == "MiniMaxH3TurboLoRA")
    if lora["widgets_values"][0] != "minimax_h3_turbo_v4_step600_ema.safetensors":
        errors.append("Turbo v4 LoRA mismatch")
    scheduler = next(node for node in nodes.values() if node.get("type") == "BasicScheduler")
    if scheduler["widgets_values"][1] != 8:
        errors.append("scheduler is not 8 steps")
    save = next(
        node
        for node in top_nodes.values()
        if node.get("type") == "H3Idea2VideoProjectVideoSave"
    )
    if save["widgets_values"][0] != "$IDEA2VIDEO_PROJECT_ROOT":
        errors.append("project output root token mismatch")
    if not str(save["widgets_values"][1]).endswith(".mp4"):
        errors.append("project output path mismatch")
    if float(save["widgets_values"][2]) != 18.0:
        errors.append("H.264/CRF 18 output mismatch")
    output_link = next(
        link
        for link in subgraph["links"]
        if int(link["target_id"]) == -20 and int(link["target_slot"]) == 0
    )
    create_video = nodes[int(output_link["origin_id"])]
    if create_video["widgets_values"] != [FPS, 10]:
        errors.append("FPS or bit depth mismatch")
    return errors


def build_workflow(source: dict[str, Any], mode: str) -> dict[str, Any]:
    if mode not in OUTPUT_FILENAMES:
        raise ValueError(f"Unsupported mode: {mode}")
    workflow = copy.deepcopy(source)
    _configure_top_level(workflow, mode)
    _configure_subgraph(workflow, mode)
    workflow.setdefault("extra", {})["h3_prompt_studio"] = {
        "mode": mode,
        "source_template": DEFAULT_SOURCE.name,
        "model_frames": MODEL_FRAMES,
        "output_frames": OUTPUT_FRAMES,
        "fps": FPS,
        "duration_seconds": DURATION_SECONDS,
        "selected_indices": SELECTED_INDICES,
        "dropped_indices": [
            index for index in range(MODEL_FRAMES) if index not in SELECTED_INDICES
        ],
        "endpoint_policy": {
            "T2VA": "generated endpoints",
            "I2VA": "exact Picture 1 at output frame 0",
            "FL2VA": "exact Picture 1 at frame 0 and exact Picture 2 at frame 167",
        }[mode],
        "project_output": {
            "root": "$IDEA2VIDEO_PROJECT_ROOT",
            "directory": "runs/manual_exports",
            "node": "H3Idea2VideoProjectVideoSave",
        },
    }
    errors = validate_workflow(workflow, mode)
    if errors:
        raise ValueError("; ".join(errors))
    return workflow


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    args = parser.parse_args()

    source_path = args.source.resolve()
    output_dir = args.output_dir.resolve()
    if not source_path.is_file():
        raise SystemExit(f"Source workflow not found: {source_path}")
    output_dir.mkdir(parents=True, exist_ok=True)
    with source_path.open("r", encoding="utf-8") as handle:
        source = json.load(handle)

    for mode, filename in OUTPUT_FILENAMES.items():
        workflow = build_workflow(source, mode)
        destination = output_dir / filename
        with destination.open("w", encoding="utf-8", newline="\n") as handle:
            json.dump(workflow, handle, ensure_ascii=False, indent=2)
            handle.write("\n")
        print(f"Built {mode}: {destination}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
